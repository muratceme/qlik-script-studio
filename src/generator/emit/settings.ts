/** Code page used for `ansi` CSV files per locale. */
export const ANSI_CODEPAGE: Record<Locale, number> = { en: 1252, tr: 1254 };

export function emitSettings(ctx: Context, w: ScriptWriter): void {
  const { project } = ctx;
  w.section('Main');
  w.comment('Generated by Qlik Script Studio (https://github.com/muratceme/qlik-script-studio)');
  w.comment(`Project: ${project.name}`);
  w.comment(
    'This script is generated from a visual model. Edit the model and regenerate instead of editing by hand.',
  );
  w.blank();
  w.comment(`Regional settings (${project.settings.locale.toUpperCase()})`);
  for (const [name, value] of REGIONAL_PRESETS[project.settings.locale]) {
    w.line(`SET ${name}=${value};`);
  }
}
